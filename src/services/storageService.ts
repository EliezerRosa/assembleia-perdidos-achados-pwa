/**
 * Carrega a base local com migração segura v1 → v2 (100% retrocompatível).
 */
export function loadDatabase(): AppDatabase {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return createEmptyDatabase();
    const parsed = JSON.parse(raw) as Partial<AppDatabase>;
    const base = createEmptyDatabase();
    return {
      ...base,
      ...parsed,
      schemaVersion: SCHEMA_VERSION,
      config: {
        ...base.config,
        ...(parsed.config ?? {}),
      },
      eventos: Array.isArray(parsed.eventos) ? parsed.eventos : [],
      itens: Array.isArray(parsed.itens) ? parsed.itens : [],
      procurados: Array.isArray(parsed.procurados) ? parsed.procurados : [],
      relatorios: Array.isArray(parsed.relatorios) ? parsed.relatorios : [],
      tiposPersonalizados: Array.isArray(parsed.tiposPersonalizados) ? parsed.tiposPersonalizados : [],
      voluntarios: Array.isArray(parsed.voluntarios) ? parsed.voluntarios : [],
      conversas: Array.isArray(parsed.conversas) ? parsed.conversas : [],
      programaPartes: Array.isArray(parsed.programaPartes) ? parsed.programaPartes : [],
      participacoes: Array.isArray(parsed.participacoes) ? parsed.participacoes : [],
      guiaAV: Array.isArray(parsed.guiaAV) ? parsed.guiaAV : [],
      lembretes: Array.isArray(parsed.lembretes) ? parsed.lembretes : [],
      referencias: Array.isArray(parsed.referencias) ? parsed.referencias : [],
      sentinelaEstudos: Array.isArray(parsed.sentinelaEstudos) ? parsed.sentinelaEstudos : [],
      sentinelaComentarios: Array.isArray(parsed.sentinelaComentarios) ? parsed.sentinelaComentarios : [],
      syncHistory: Array.isArray(parsed.syncHistory) ? parsed.syncHistory : [],
    };
  } catch {
    return createEmptyDatabase();
  }
}

export function saveDatabase(db: AppDatabase): { ok: boolean; error?: string; bytesUsed: number } {
  try {
    const serialized = JSON.stringify(db);
    localStorage.setItem(STORAGE_KEY, serialized);
    return { ok: true, bytesUsed: serialized.length * 2 };
  } catch (err) {
    const isQuota =
      err instanceof DOMException &&
      (err.name === 'QuotaExceededError' || err.code === 22 || err.code === 1014);
    return {
      ok: false,
      bytesUsed: 0,
      error: isQuota
        ? 'Limite do localStorage atingido! Exporte um backup JSON na aba Sincronizar ou remova áudios/eventos antigos.'
        : 'Erro ao gravar dados no localStorage.',
    };
  }
}

export function getStorageUsage(): {
  bytesUsed: number;
  kbUsed: number;
  mbUsed: number;
  percentUsed: number;
  nearLimit: boolean;
} {
  try {
    const raw = localStorage.getItem(STORAGE_KEY) ?? '';
    const bytesUsed = raw.length * 2; // UTF-16 aproximado
    const kbUsed = Math.round(bytesUsed / 1024);
    const mbUsed = Number((bytesUsed / (1024 * 1024)).toFixed(2));
    const percentUsed = Math.min(100, Math.round((bytesUsed / ESTIMATED_QUOTA_BYTES) * 100));
    return { bytesUsed, kbUsed, mbUsed, percentUsed, nearLimit: percentUsed >= 80 };
  } catch {
    return { bytesUsed: 0, kbUsed: 0, mbUsed: 0, percentUsed: 0, nearLimit: false };
  }
}

